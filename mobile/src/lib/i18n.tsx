const DICTS: Record<Lang, Dict> = { vi, de };
const STORE_KEY = "app-lang";

export type TParams = Record<string, string | number>;
export type TFn = (key: Key, params?: TParams) => string;

function translate(lang: Lang, key: Key, params?: TParams): string {
  const d = DICTS[lang];
  const one = params?.n === 1 ? d[`${key}_one`] : undefined;
  const s = one ?? d[key] ?? vi[key];
  return params ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : s;
}

function deviceLang(): Lang {
  try {
    const code = Intl.DateTimeFormat().resolvedOptions().locale.slice(0, 2).toLowerCase();
    return code === "de" ? code : "vi";
  } catch {
    return "vi";
  }
}

// Ngôn ngữ hiện tại cho code ngoài React (thông báo lỗi trong api.ts)
let current: Lang = deviceLang();
export const t: TFn = (key, params) => translate(current, key, params);
/** Ngôn ngữ đang dùng (đọc được ngoài React, luôn là giá trị mới nhất) */
export const currentLang = () => current;

type I18n = { lang: Lang; setLang: (l: Lang) => void; t: TFn };
const I18nContext = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(current);

  useEffect(() => {
    SecureStore.getItemAsync(STORE_KEY)
      .then((saved) => {
        if (isLang(saved)) {
          current = saved;
          setLangState(saved);
        }
      })
      .catch(() => {});
  }, []);

  const setLang = useCallback((l: Lang) => {
    current = l;
    setLangState(l);
    SecureStore.setItemAsync(STORE_KEY, l).catch(() => {});
  }, []);

  const value = useMemo<I18n>(() => ({ lang, setLang, t: (key, params) => translate(lang, key, params) }), [lang, setLang]);
  return <I18nContext value={value}>{children}</I18nContext>;
}

export function useI18n(): I18n {
  const v = use(I18nContext);
  if (!v) throw new Error("useI18n phải nằm trong <I18nProvider>");
  return v;
}
